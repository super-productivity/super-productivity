import { isValidSplitTime } from '../../util/is-valid-split-time';
import { remindOptionToMilliseconds } from '../tasks/util/remind-option-to-milliseconds';
import { getRepeatableTaskId } from './get-repeatable-task-id.util';
import { getRepeatDueWithTime } from './store/get-repeat-due-with-time.util';
import { selectTaskRepeatCfgsForExactDay } from './store/task-repeat-cfg.selectors';
import { TaskRepeatCfg } from './task-repeat-cfg.model';

/**
 * How many days ahead recurring reminders are pre-scheduled. Every occurrence
 * in this window is armed (up to {@link REPEAT_MAX_SCHEDULED}), because nothing
 * re-arms the next one while the app is closed: the native side only shows
 * alarms and restores them on reboot (#10781). Longer-period configs (e.g.
 * monthly) are picked up the next time the app is opened within this window.
 * See #7850.
 *
 * The Android background worker ports this function (RepeatReminderSchedule.kt).
 * Keep them in step via android/app/src/test/resources/repeat-reminder-fixtures.json,
 * regenerated by tools/generate-repeat-reminder-fixtures.mjs.
 */
export const REPEAT_LOOKAHEAD_DAYS = 14;

/**
 * Android upper bound on how many recurring reminders are pre-scheduled in one
 * pass (Android allows ~500 alarms per app). Over the cap, keep every config's
 * next occurrence before any config's second (then soonest first), so a weekly
 * config is never crowded out by daily ones. Truncation is logged, never silent.
 * shortcut: with many timed daily configs the app-closed coverage shrinks to
 * 32 / configs days (e.g. 5 configs → ~6 days) — raise it if users report gaps.
 */
export const REPEAT_MAX_SCHEDULED = 32;

export interface UpcomingRepeatReminder {
  taskId: string;
  triggerAtMs: number;
  title: string;
}

export interface UpcomingRepeatReminderLimits {
  lookaheadDays: number;
  maxScheduled: number;
  /**
   * iOS fills a shared notification budget soonest-first. Android keeps each
   * config's nearer occurrences first.
   */
  soonestFirst: boolean;
}

/**
 * Upcoming timed occurrences that still need a native reminder.
 *
 * Reuses {@link selectTaskRepeatCfgsForExactDay}'s projector per day so the
 * isPaused / already-created / deletedInstanceDates guards stay in lockstep
 * with instance creation. Time computation mirrors TaskRepeatCfgService, so
 * the pre-scheduled trigger matches the real instance. `archivedProjectIds`
 * applies the same filter as selectActiveTaskRepeatCfgs; the in-app effect
 * passes configs that selector already narrowed, and omits the set.
 */
export const getUpcomingRepeatReminders = (
  cfgs: readonly TaskRepeatCfg[] | null | undefined,
  now: number,
  startOfNextDayDiffMs: number,
  limits: UpcomingRepeatReminderLimits,
  archivedProjectIds?: ReadonlySet<string>,
): UpcomingRepeatReminder[] => {
  const archived = archivedProjectIds ?? new Set<string>();
  const activeCfgs = (cfgs ?? []).filter(
    (cfg) => archived.size === 0 || !cfg.projectId || !archived.has(cfg.projectId),
  );
  const result: (UpcomingRepeatReminder & { rank: number })[] = [];
  const countByCfgId = new Map<string, number>();

  // Anchor each day at noon to keep the per-day timestamp clear of DST /
  // midnight edges; getDbDateStr/getRepeatDueWithTime only use the date.
  // Start from the logical day: between midnight and the start of the next
  // day, the previous day's late occurrence is still upcoming.
  const baseDay = new Date(now - startOfNextDayDiffMs);
  baseDay.setHours(12, 0, 0, 0);

  for (let dayOffset = 0; dayOffset <= limits.lookaheadDays; dayOffset++) {
    const day = new Date(baseDay);
    day.setDate(baseDay.getDate() + dayOffset);
    const dayMs = day.getTime();

    const dueCfgs =
      selectTaskRepeatCfgsForExactDay.projector(activeCfgs, { dayDate: dayMs }) || [];

    for (const cfg of dueCfgs) {
      const cfgId = cfg.id as string;
      // waitForCompletion: the next instance only exists once the current one
      // is completed, so its occurrence cannot be reliably pre-scheduled.
      if (cfg.waitForCompletion) {
        continue;
      }
      if (!isValidSplitTime(cfg.startTime) || !cfg.remindAt) {
        continue;
      }

      const dueMs = getRepeatDueWithTime(cfg.startTime, dayMs, startOfNextDayDiffMs);
      const triggerAtMs = remindOptionToMilliseconds(dueMs, cfg.remindAt);
      if (typeof triggerAtMs !== 'number' || triggerAtMs <= now) {
        continue;
      }

      const rank = countByCfgId.get(cfgId) ?? 0;
      countByCfgId.set(cfgId, rank + 1);
      result.push({
        taskId: getRepeatableTaskId(cfgId, getDbDateStr(dayMs)),
        triggerAtMs,
        title: cfg.title || '',
        rank,
      });
    }
  }

  if (limits.soonestFirst) {
    return result
      .sort((a, b) => a.triggerAtMs - b.triggerAtMs)
      .slice(0, limits.maxScheduled)
      .map(({ taskId, triggerAtMs, title }) => ({ taskId, triggerAtMs, title }));
  }

  // Over the cap, keep each config's nearer occurrences first, soonest first
  // within a rank (see REPEAT_MAX_SCHEDULED). Sort explicitly so the cap is
  // deterministic.
  result.sort((a, b) => a.rank - b.rank || a.triggerAtMs - b.triggerAtMs);
  if (result.length > limits.maxScheduled) {
    Log.log('MobileEffects: capping pre-scheduled repeat reminders', {
      total: result.length,
      cap: limits.maxScheduled,
    });
  }

  return result
    .slice(0, limits.maxScheduled)
    .map(({ taskId, triggerAtMs, title }) => ({ taskId, triggerAtMs, title }));
};
